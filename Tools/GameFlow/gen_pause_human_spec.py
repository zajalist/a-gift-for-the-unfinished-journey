"""Pause in Human (task ENDING, brief step 4): PC_Saskarta.pause.json, a scoped spec for --reset-graphs.

    python Tools/GameFlow/gen_pause_human_spec.py   # -> specs/PC_Saskarta.pause.json

The canonical P3 generator (gen_settings_specs.mjs pcGraphs) owns the Human pause fix.
This extracts its three current graphs from PC_Saskarta.json without patching them again:
- TogglePause and OpenPause open when FlowState is Playing OR Human;
- OpenPause stores PausedFrom = FlowState before FlowState = Paused;
- ClosePause restores FlowState = PausedFrom (a new Name variable, default Playing) instead of the literal.
Transmit and End stay unpausable (no input there). Regenerating P3 or this scoped spec preserves
the same state transitions. A stale canonical source is rejected rather than silently masked here.
"""
import copy
import json
import re
from pathlib import Path

SPECS = Path(__file__).resolve().parent / "specs"


def load(p):
    return json.loads(re.sub(r"^\s*//.*$", "", p.read_text(encoding="utf-8"), flags=re.M))


def main():
    pc = load(SPECS / "PC_Saskarta.json")
    graphs = {g["graph"]: copy.deepcopy(g) for g in pc["graphs"] if g["graph"] in ("TogglePause", "OpenPause", "ClosePause")}
    t, o, c = graphs["TogglePause"], graphs["OpenPause"], graphs["ClosePause"]
    for g, pin in ((t, "br.Condition"), (o, "guard.Condition")):
        assert g["defaults"].get("isPlayingHuman.B") == "Human", "Regenerate the canonical Human-aware pause graphs first"
        assert ["orHuman.ReturnValue", pin] in g["links"]
    assert ["guard.then", "savePrev.execute"] in o["links"]
    assert ["savePrev.then", "toPaused.execute"] in o["links"]
    assert ["getFlowStateF.FlowState", "savePrev.PausedFrom"] in o["links"]
    assert ["getPausedFrom.PausedFrom", "toPlaying.FlowState"] in c["links"]
    assert "toPlaying.FlowState" not in c["defaults"]
    assert {"name": "PausedFrom", "type": "name", "default": "Playing"} in pc["variables"]
    used = {n.get("get") or n.get("set") for g in (t, o, c) for n in g["nodes"].values()}
    variables = [v for v in pc["variables"] if v["name"] in used and v["name"] != "PausedFrom"] + [{"name": "PausedFrom", "type": "name", "default": "Playing"}]
    spec = {"asset": pc["asset"],
            "description": "Scoped rebuild (task ENDING, generated by gen_pause_human_spec.py): Esc pauses in Playing and Human, "
                           "and ClosePause restores the state it paused from. Build with --reset-graphs.",
            "variables": variables,
            "functions": [f for f in pc["functions"] if f["name"] in ("TogglePause", "OpenPause", "ClosePause")],
            "graphs": [t, o, c]}
    (SPECS / "PC_Saskarta.pause.json").write_text(json.dumps(spec, indent=1) + "\n", encoding="utf-8")
    print("wrote PC_Saskarta.pause.json:", ", ".join(g["graph"] for g in spec["graphs"]))


if __name__ == "__main__":
    main()
