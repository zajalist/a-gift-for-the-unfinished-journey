"""Generate the scoped first-boot skip graph and apply CIN_01's first-play skip policy.

    python Tools/GameFlow/gen_opening_skip.py

This does not build assets or contact the editor. Build the emitted BPC spec before the
PC loading spec because PC_Saskarta.PollOpeningSkip calls BPC_CarrierVision.SkipBoot.
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SPECS = HERE / "specs"
EVENTS = ROOT / "docs" / "story" / "story-events.json"

ENGINE = "/Script/Engine"
KML = ENGINE + ".KismetMathLibrary"
KSL = ENGINE + ".KismetSystemLibrary"
CV = "/Game/SaskartaGaea/GameFlow/BPC_CarrierVision"


def call(name, cls=None):
    return {"call": name, "class": cls} if cls else {"call": name}


def skip_boot_graph():
    nodes = {
        "entry": {"entry": True},
        "request": {"set": "bSkipBootRequested"},
        "kind": {"get": "BootKind"},
        "firstBoot": call("EqualEqual_NameName", KML),
        "applied": {"get": "bSkipBootApplied"},
        "notApplied": call("Not_PreBool", KML),
        "eligible": call("BooleanAND", KML),
        "branch": {"branch": True},
        "sequence": {"sequence": 4},
        "markApplied": {"set": "bSkipBootApplied"},
        "clearRequest": {"set": "bSkipBootRequested"},
        "lineTimer": {"get": "LineTimer"},
        "clearLine": call("K2_ClearAndInvalidateTimerHandle", KSL),
        "powerOn": call("PowerOn"),
    }
    links = [
        ["entry.then", "request.execute"],
        ["request.then", "branch.execute"],
        ["kind.BootKind", "firstBoot.A"],
        ["firstBoot.ReturnValue", "eligible.A"],
        ["applied.bSkipBootApplied", "notApplied.A"],
        ["notApplied.ReturnValue", "eligible.B"],
        ["eligible.ReturnValue", "branch.Condition"],
        ["branch.then", "sequence.execute"],
        ["sequence.then_0", "markApplied.execute"],
        ["sequence.then_1", "clearRequest.execute"],
        ["sequence.then_2", "clearLine.execute"],
        ["sequence.then_3", "powerOn.execute"],
        ["lineTimer.LineTimer", "clearLine.Handle"],
    ]
    defaults = {
        "request.bSkipBootRequested": "true",
        "firstBoot.B": "FirstBoot",
        "markApplied.bSkipBootApplied": "true",
        "clearRequest.bSkipBootRequested": "false",
    }
    return {"graph": "SkipBoot", "nodes": nodes, "links": links, "defaults": defaults}


def build_spec():
    base = json.loads((SPECS / "BPC_CarrierVision.json").read_text(encoding="utf-8"))
    variables = list(base["variables"])
    variables.extend([
        {"name": "bSkipBootRequested", "type": "bool", "default": "false"},
        {"name": "bSkipBootApplied", "type": "bool", "default": "false"},
    ])
    return {
        "asset": CV,
        "description": "Scoped safe skip for the FirstBoot terminal narrative. It waits until PlayBoot has initialized BootKind, then uses the normal PowerOn -> VisionOnline path. Generated by gen_opening_skip.py.",
        "variables": variables,
        "functions": [{"name": "SkipBoot", "pure": False, "inputs": [], "outputs": []}],
        "graphs": [skip_boot_graph()],
    }


def apply_cin01_policy():
    source = EVENTS.read_text(encoding="utf-8")
    doc = json.loads(source)
    events = doc.get("cinematics", {})
    cine = events.get("CIN_01_DIRECTIVE")
    if not isinstance(cine, dict):
        raise ValueError("CIN_01_DIRECTIVE not found in docs/story/story-events.json")
    if cine.get("skip") not in {"HoldAfterSeen", "HoldAlways"}:
        raise ValueError(f"unexpected CIN_01 skip policy: {cine.get('skip')!r}")
    if float(cine.get("skip_min_s", 0.0)) != 1.0:
        raise ValueError(f"unexpected CIN_01 skip_min_s: {cine.get('skip_min_s')!r}")
    if cine["skip"] == "HoldAlways":
        return

    key = '"CIN_01_DIRECTIVE"'
    key_at = source.find(key)
    if key_at < 0:
        raise ValueError("CIN_01_DIRECTIVE key not found in source text")
    object_at = source.find("{", key_at + len(key))
    if object_at < 0:
        raise ValueError("CIN_01_DIRECTIVE object not found in source text")
    depth = 0
    in_string = False
    escaped = False
    object_end = -1
    for i in range(object_at, len(source)):
        ch = source[i]
        if in_string:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                object_end = i + 1
                break
    if object_end < 0:
        raise ValueError("unterminated CIN_01_DIRECTIVE object")
    start, end = object_at, object_end
    snippet = source[start:end]
    match = re.search(r'("skip"\s*:\s*)"HoldAfterSeen"', snippet)
    if not match:
        raise ValueError("CIN_01_DIRECTIVE skip field did not match parsed value")
    replacement = match.group(1) + '"HoldAlways"'
    EVENTS.write_text(source[:start] + snippet[:match.start()] + replacement + snippet[match.end():] + source[end:],
                      encoding="utf-8")


def main():
    apply_cin01_policy()
    (SPECS / "BPC_CarrierVision.opening_skip.json").write_text(
        json.dumps(build_spec(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print("wrote Tools/GameFlow/specs/BPC_CarrierVision.opening_skip.json")
    print("set CIN_01_DIRECTIVE skip=HoldAlways (all other event fields preserved)")


if __name__ == "__main__":
    main()
